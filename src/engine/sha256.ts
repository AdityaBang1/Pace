/**
 * SHA-256, because identity has to agree with the Python reader.
 *
 * Hermes has no synchronous WebCrypto, `expo-crypto` is async-only for digests
 * of arbitrary data, and IDs are needed inside a synchronous record build. The
 * hashes are over short strings (a few hundred bytes), so a plain implementation
 * is cheaper than an async boundary through every id.
 */

